import marimo

__generated_with = "0.25.2"
app = marimo.App(width="full")


@app.cell
def _():
    import marimo as mo
    from pedalutils import PedalDataset
    import matplotlib.pyplot as plt
    import numpy as np

    return PedalDataset, mo, np, plt


@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    # DataSet Testing

    This note book will load in a data set generated by the training tool and allow the user to playback samples.
    """)
    return


@app.cell(hide_code=True)
def _(mo):
    loader_ui = mo.ui.dictionary(
        {
            "file": mo.ui.file_browser(
                filetypes=[".json"],
                multiple=False,
                restrict_navigation=False,
                label="Manifest file",
            )
        }
    ).form(submit_button_label="Load")
    loader_ui
    return (loader_ui,)


@app.cell
def _(PedalDataset, loader_ui, mo):
    _settings = loader_ui.value
    mo.stop(
        _settings is None or not _settings["file"],
        mo.md("Select a manifest file and press Load."),
    )
    dataset = PedalDataset(_settings["file"][0].path)
    print(f"Dataset loaded have found {len(dataset)} Samples")
    number_of_samples = len(dataset) - 1
    return dataset, number_of_samples


@app.cell(hide_code=True)
def _(mo, number_of_samples):
    selected_sample = mo.ui.slider(
        start=0, stop=number_of_samples, label="Select Sample", show_value=True
    )
    return (selected_sample,)


@app.cell
def _():
    return


@app.cell
def _(dataset, mo, np, plt, selected_sample):
    current_sample = dataset[selected_sample.value]

    figure, _axes = plt.subplots(
        2, 1, figsize=(12, 5), sharex=True, sharey=True, layout="constrained"
    )
    for _axis, _signal, _label, _colour in zip(
        _axes,
        current_sample[:2],
        ("Dry signal", "Wet signal"),
        ("tab:blue", "tab:orange"),
    ):
        _audio = _signal.detach().cpu().numpy()
        _time = np.arange(_audio.shape[-1]) / dataset._sample_rate
        for _channel, _values in enumerate(_audio):
            _axis.plot(
                _time,
                _values,
                color=_colour,
                linewidth=0.7,
                label=f"Channel {_channel + 1}",
            )
        _axis.set_title(_label)
        _axis.set_ylabel("Amplitude")
        _axis.grid(alpha=0.25)
        if _audio.shape[0] > 1:
            _axis.legend()
    _axes[-1].set_xlabel("Time (s)")

    mo.vstack(
        [
            mo.hstack(
                [
                    selected_sample,
                    mo.md(
                        f"Controls **{dataset.control_labels[0]}** {current_sample[2][0]} **{dataset.control_labels[1]}** {current_sample[2][1]} **{dataset.control_labels[2]}** {current_sample[2][2]}"
                    ),
                ]
            ),
            mo.hstack(
                [
                    mo.vstack(
                        [
                            mo.md(
                                "**Dry signal**\nOriginal recording before processing."
                            ),
                            mo.audio(
                                src=current_sample[0],
                                rate=44000,
                                normalize=True,
                            ),
                        ]
                    )
                ]
            ),
            mo.vstack(
                [
                    mo.md(
                        "**Wet signal**\nOriginal recording after processing."
                    ),
                    mo.audio(
                        src=current_sample[1], rate=44000, normalize=True
                    ),
                ]
            ),
            figure,
        ]
    )
    return


if __name__ == "__main__":
    app.run()
